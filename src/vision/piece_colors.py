"""テトリミノの色定義（ぷよぷよテトリス風パレット）

画面認識で色をサンプリングした際の判定基準と、
オーバーレイ描画で使う表示色を一元管理する。

実機（ぷよぷよテトリス）の映像を解析したところ、同じミノでも
「操作中は明るく、着地後は影で暗く」表示が変わることが分かった（明度Vが変動する）。
RGB距離での分類は明度差に弱く誤判定するため、明度に左右されにくい
色相(Hue)を基準に判定する。
"""

from __future__ import annotations

from typing import NamedTuple


class RGB(NamedTuple):
    r: int
    g: int
    b: int


# 表示用（オーバーレイ描画色）。すべてぷよぷよテトリスの実機映像からサンプリングした値。
PIECE_COLORS: dict[str, RGB] = {
    "I": RGB(12, 188, 224),   # 水色
    "O": RGB(254, 201, 1),    # 黄
    "T": RGB(142, 22, 160),   # 紫
    "S": RGB(106, 211, 23),   # 緑
    "Z": RGB(203, 0, 32),     # 赤
    "J": RGB(8, 143, 195),    # 青（Iより明度が低い水色寄りの青）
    "L": RGB(245, 142, 6),    # 橙
    "GARBAGE": RGB(120, 120, 120),  # おじゃまブロック（灰色）
    "EMPTY": RGB(30, 45, 37),       # 空セル（盤面背景。緑がかった暗色）
}

# IとJは色相(Hue)だけでは近すぎて区別しづらいため、明度(Value)も判定に使う。
# 実サンプルでは I: V≈0.88、J: V≈0.77 と明確な差がある。
I_J_VALUE_THRESHOLD = 0.82

# GARBAGE/EMPTYを除いた、実ミノ7種の名前一覧
ALL_PIECE_NAMES: frozenset[str] = frozenset({"I", "O", "T", "S", "Z", "J", "L"})
